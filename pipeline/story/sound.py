"""Soundtrack for storyboard reels: voice bus + SFX bus + music bus, ducked and
mixed from the timeline.

SFX: every cue in spec.SFX_CUES has a procedural version (always available).
     With ELEVENLABS_API_KEY set (and GG_AI_SFX != 0) cues are generated by the
     ElevenLabs sound-effects model from a text prompt instead, and cached.
Music: drop licensed tracks into assets/music/<mood>/ (mp3/wav) and one is
     picked deterministically per video; otherwise a procedural bed is used.
"""
import hashlib
import json
import os
import urllib.request
import wave
from pathlib import Path

import numpy as np

from .voice import ROOT, SR, decode

SFX_CACHE = ROOT / "cache" / "sfx"
MUSIC_DIR = ROOT / "assets" / "music"

SFX_PROMPTS = {
    "pop": "cartoon pop", "whoosh": "fast cartoon whoosh", "tick": "clock ticking fast",
    "card_flip": "playing card flipped onto felt table", "chips": "poker chips stacking",
    "boing": "cartoon boing", "sting": "dramatic orchestral reveal sting",
    "impact": "cinematic impact hit", "crickets": "crickets chirping awkward silence",
    "dice_roll": "two dice rolling on a wooden table", "thud": "soft cartoon thud",
    "ding": "bright bell ding", "glitch": "digital glitch burst", "riser": "tension riser",
    "boom": "deep cinematic boom", "waves": "ocean waves against a ship hull",
    "wind": "wind over open fields", "hammer": "hammer hitting wooden beam",
    "engine": "powerful futuristic boat engines approaching", "hoofbeats": "cavalry horses galloping",
    "crowd": "medieval crowd shouting", "horn": "distant war horn", "coins": "coins clinking",
    "sword": "sword drawn from sheath",
}
AMBIENT = {"waves", "wind", "engine", "crowd", "crickets", "hoofbeats"}


# ---------------- DSP helpers ----------------
def _t(dur):
    return np.arange(int(dur * SR)) / SR


def _env(n, attack=0.002, decay=0.2):
    t = np.arange(n) / SR
    return np.clip(t / max(attack, 1e-4), 0, 1) * np.exp(-t / decay)


def _filt(x, lo=None, hi=None):
    """Smooth FFT band filter (lo/hi in Hz)."""
    if len(x) < 4:
        return x
    X = np.fft.rfft(x)
    f = np.fft.rfftfreq(len(x), 1 / SR)
    g = np.ones_like(f)
    if hi:
        g /= 1 + (f / hi) ** 4
    if lo:
        g *= 1 - 1 / (1 + (f / lo) ** 4)
    return np.fft.irfft(X * g, len(x))


def _norm(x, peak=1.0):
    return x / (np.abs(x).max() + 1e-9) * peak


def _sweep(f0, f1, dur, decay=None, attack=0.003):
    n = int(dur * SR)
    f = np.geomspace(f0, f1, n)
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * _env(n, attack, decay or dur / 2.5)


def _noise(dur, rng):
    return rng.standard_normal(int(dur * SR))


def _saw(freq, dur):
    t = _t(dur)
    return 2 * ((freq * t) % 1.0) - 1


def _pluck(freq, dur=0.6, bright=3):
    t = _t(dur)
    s = sum(np.sin(2 * np.pi * freq * k * t) * np.exp(-t * (5 + 4 * k)) / k for k in range(1, bright + 1))
    return s * np.clip(t / 0.002, 0, 1)


def _add(buf, sig, t0, gain=1.0):
    i = int(t0 * SR)
    if i < 0:
        sig, i = sig[-i:], 0
    if i >= len(buf):
        return
    j = min(len(buf), i + len(sig))
    buf[i:j] += sig[: j - i] * gain


# ---------------- procedural SFX ----------------
def procedural(cue, rng, dur=None):
    if cue == "pop":
        return _sweep(380, 980, 0.09, 0.05)
    if cue == "whoosh":
        n = _filt(_noise(0.5, rng), 300, 3000)
        return _norm(n * np.sin(np.linspace(0, np.pi, len(n))) ** 2, 0.8)
    if cue == "tick":
        out = np.zeros(int((dur or 1.0) * SR))
        for k in range(int((dur or 1.0) / 0.12)):
            _add(out, _filt(_noise(0.012, rng), 2000) * _env(int(0.012 * SR), 0.0005, 0.003), k * 0.12, 0.7)
        return out
    if cue == "card_flip":
        a = _filt(_noise(0.05, rng), 1500) * _env(int(0.05 * SR), 0.001, 0.012)
        b = np.zeros(int(0.1 * SR))
        _add(b, a, 0)
        _add(b, a, 0.045, 0.6)
        return _norm(b, 0.7)
    if cue == "chips":
        out = np.zeros(int(0.5 * SR))
        for k in range(7):
            click = _sweep(3200 + rng.uniform(-400, 400), 2600, 0.03, 0.008)
            _add(out, click, k * 0.05 + rng.uniform(0, 0.02), rng.uniform(0.4, 0.9))
        return out
    if cue == "boing":
        t = _t(0.6)
        f = 220 * (1 + 0.3 * np.sin(2 * np.pi * 9 * t) * np.exp(-t * 4))
        return np.sin(2 * np.pi * np.cumsum(f) / SR) * _env(len(t), 0.003, 0.25)
    if cue == "sting":
        t = _t(1.8)
        chord = sum(_saw(f, 1.8) for f in (110, 130.8, 164.8, 220))
        s = _filt(chord, None, 1800) * np.exp(-t * 1.6) * 0.5
        hit = _sweep(120, 40, 1.2, 0.4) * 1.2
        s[: len(hit)] += hit
        return _norm(s, 0.95)
    if cue in ("impact", "boom"):
        s = _sweep(95 if cue == "boom" else 140, 30, 1.8, 0.6 if cue == "boom" else 0.35)
        nz = _filt(_noise(0.6, rng), None, 900) * _env(int(0.6 * SR), 0.001, 0.15) * 0.4
        s[: len(nz)] += nz
        return _norm(s, 1.0)
    if cue == "crickets":
        d = dur or 2.0
        t = _t(d)
        chirp = np.sin(2 * np.pi * 4300 * t) * (np.sin(2 * np.pi * 28 * t) > 0.3) * ((t % 0.9) < 0.25)
        return chirp * 0.25
    if cue == "dice_roll":
        out = np.zeros(int(0.9 * SR))
        tt, gap = 0.0, 0.04
        while tt < 0.8:
            _add(out, _filt(_noise(0.02, rng), 800, 5000) * _env(int(0.02 * SR), 0.0005, 0.006), tt, 0.8)
            tt += gap
            gap *= 1.18
        return out
    if cue == "thud":
        return _sweep(110, 50, 0.3, 0.09)
    if cue == "ding":
        t = _t(1.4)
        return sum(np.sin(2 * np.pi * 1318 * m * t) / m ** 2 for m in (1, 2.76, 5.4)) * _env(len(t), 0.002, 0.4)
    if cue == "glitch":
        out = np.zeros(int(0.45 * SR))
        for _ in range(9):
            f = rng.uniform(80, 2000)
            sq = np.sign(np.sin(2 * np.pi * f * _t(rng.uniform(0.02, 0.06))))
            _add(out, sq, rng.uniform(0, 0.4), rng.uniform(0.2, 0.5))
        return out
    if cue == "riser":
        d = dur or 2.0
        n = _filt(_noise(d, rng), 500, 6000) * np.linspace(0, 1, int(d * SR)) ** 2
        return _norm(n * 0.6 + _sweep(200, 1600, d, d * 3, attack=d * 0.8) * 0.4, 0.8)
    if cue == "waves":
        d = dur or 4.0
        t = _t(d)
        n = _filt(_noise(d, rng), 80, 900)
        return _norm(n * (0.35 + 0.65 * (0.5 + 0.5 * np.sin(2 * np.pi * t / 3.2 - 1.2)) ** 2), 0.6)
    if cue == "wind":
        d = dur or 4.0
        t = _t(d)
        return _norm(_filt(_noise(d, rng), 200, 1200) * (0.6 + 0.4 * np.sin(2 * np.pi * t / 2.7)), 0.4)
    if cue == "hammer":
        k = _filt(_noise(0.08, rng), 400, 4000) * _env(int(0.08 * SR), 0.0005, 0.02)
        tone = _sweep(220, 160, 0.12, 0.04) * 0.6
        tone[: len(k)] += k
        return _norm(tone, 0.9)
    if cue == "engine":
        d = dur or 4.0
        t = _t(d)
        s = _filt(_saw(46, d) + 0.5 * _saw(69.5, d), None, 400) + _filt(_noise(d, rng), 100, 700) * 0.4
        return _norm(s * np.clip(t / (d * 0.7), 0.2, 1), 0.6)
    if cue == "hoofbeats":
        d = dur or 3.0
        out = np.zeros(int(d * SR))
        tt = 0.0
        while tt < d:
            for off in (0, 0.09, 0.2):
                _add(out, _sweep(140, 60, 0.12, 0.03), tt + off, 0.7)
            tt += 0.42
        return out
    if cue == "crowd":
        d = dur or 3.0
        t = _t(d)
        n = _filt(_noise(d, rng), 250, 2200)
        return _norm(n * (0.5 + 0.5 * np.abs(np.sin(2 * np.pi * 1.7 * t) * np.sin(2 * np.pi * 0.6 * t))), 0.5)
    if cue == "horn":
        t = _t(2.2)
        s = _filt(_saw(98, 2.2) + 0.6 * _saw(147, 2.2), None, 700)
        return _norm(s * np.clip(t / 0.4, 0, 1) * np.exp(-np.clip(t - 1.4, 0, None) * 3), 0.7)
    if cue == "coins":
        out = np.zeros(int(0.6 * SR))
        for k in range(5):
            _add(out, np.sin(2 * np.pi * rng.uniform(3000, 5200) * _t(0.25)) * _env(int(0.25 * SR), 0.001, 0.06),
                 k * 0.07, 0.5)
        return out
    if cue == "sword":
        t = _t(1.0)
        ring = sum(np.sin(2 * np.pi * f * t) for f in (2400, 3700, 5100)) * _env(len(t), 0.05, 0.35)
        return _norm(ring + _filt(_noise(1.0, rng), 3000) * _env(len(t), 0.01, 0.12), 0.6)
    raise KeyError(cue)


def ai_sfx(cue, prompt, dur):
    """ElevenLabs sound-generation, cached. Returns None when unavailable."""
    key = os.environ.get("ELEVENLABS_API_KEY")
    if not key or os.environ.get("GG_AI_SFX", "1") == "0":
        return None
    text = prompt or SFX_PROMPTS[cue]
    body = {"text": text}
    if dur:
        body["duration_seconds"] = round(min(22.0, max(0.5, dur)), 1)
    h = hashlib.sha1(json.dumps(body).encode()).hexdigest()[:16]
    SFX_CACHE.mkdir(parents=True, exist_ok=True)
    path = SFX_CACHE / f"{cue}_{h}.mp3"
    if not path.exists():
        try:
            req = urllib.request.Request("https://api.elevenlabs.io/v1/sound-generation",
                                         data=json.dumps(body).encode(), method="POST",
                                         headers={"xi-api-key": key, "Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=120) as r:
                path.write_bytes(r.read())
        except Exception as e:  # never fail a render over an SFX
            print(f"  ai sfx '{cue}' failed ({e}); using procedural")
            return None
    return decode(path)


def cue_audio(cue, rng, dur=None, prompt=None):
    a = ai_sfx(cue, prompt, dur if cue in AMBIENT else None)
    if a is None:
        a = procedural(cue, rng, dur)
    if dur and cue in AMBIENT:  # loop/trim ambience to the shot, with fades
        n = int(dur * SR)
        a = np.tile(a, n // max(1, len(a)) + 1)[:n]
        f = min(n // 4, int(0.3 * SR))
        if f:
            a[:f] *= np.linspace(0, 1, f)
            a[-f:] *= np.linspace(1, 0, f)
    return a.astype(np.float64)


# ---------------- music ----------------
SCALES = {
    "quirky": ([0, 2, 4, 7, 9], 105, 261.6, False),
    "tense": ([0, 1, 5, 7, 8], 92, 220.0, True),
    "epic": ([0, 2, 3, 5, 7, 8, 10], 88, 146.8, True),
    "dark": ([0, 1, 3, 6, 7], 76, 130.8, True),
    "triumph": ([0, 2, 4, 5, 7, 9, 11], 96, 196.0, False),
}


def music_bed(mood, total, seed):
    lib = sorted((MUSIC_DIR / mood).glob("*.*")) if (MUSIC_DIR / mood).exists() else []
    lib = [p for p in lib if p.suffix.lower() in (".mp3", ".wav", ".m4a", ".ogg", ".flac")]
    if lib:
        a = decode(lib[seed % len(lib)]).astype(np.float64)
        n = int(total * SR)
        a = np.tile(a, n // len(a) + 1)[:n]
        return _norm(a, 0.9)
    return _procedural_music(mood, total, seed)


def _procedural_music(mood, total, seed):
    rng = np.random.default_rng(seed)
    scale, bpm, root, minor = SCALES[mood]
    beat = 60 / bpm
    n = int(total * SR) + SR
    buf = np.zeros(n)
    note = lambda deg, octv=0: root * 2 ** ((scale[deg % len(scale)] + 12 * (octv + deg // len(scale))) / 12)
    prog = [0, 5, 3, 4] if minor else [0, 3, 4, 3]
    bars = int(total / (beat * 4)) + 2
    for bar in range(bars):
        chord = prog[bar % len(prog)]
        t0 = bar * beat * 4
        if mood in ("quirky", "triumph"):
            pat = [0, 2, 4, 2, 7, 4, 2, 4]
            for k, d in enumerate(pat):
                if rng.random() < 0.85:
                    _add(buf, _pluck(note(chord + d, 1)), t0 + k * beat / 2, 0.22)
            for k in (0, 2):
                _add(buf, _pluck(note(chord, -1), 0.9, 2), t0 + k * beat, 0.4)
            for k in range(8):
                _add(buf, _filt(rng.standard_normal(int(0.03 * SR)), 6000) * _env(int(0.03 * SR), 0.0005, 0.01),
                     t0 + k * beat / 2 + beat / 4, 0.05)
        else:
            d = beat * 4
            pad = sum(_saw(note(chord + i, -1) * (1 + det), d + 0.3)
                      for i in (0, 2, 4) for det in (-0.003, 0.003))
            pad = _filt(pad, None, 900 if mood == "epic" else 500) * 0.07
            pad *= np.clip(_t(d + 0.3) / 0.3, 0, 1) * np.clip((d + 0.3 - _t(d + 0.3)) / 0.3, 0, 1)
            _add(buf, pad, t0)
            hits = [0, 1.5, 2, 3] if mood == "epic" else [0, 2.5]
            for h in hits:
                drum = _sweep(85, 38, 0.7, 0.22)
                drum[: int(0.2 * SR)] += _filt(rng.standard_normal(int(0.2 * SR)), None, 400) \
                    * _env(int(0.2 * SR), 0.001, 0.05) * 0.5
                _add(buf, drum, t0 + h * beat, 0.5 if h == 0 else 0.35)
            if mood == "epic":
                for k in range(8):
                    _add(buf, _filt(_saw(note(chord, 0), beat / 2 * 0.9), None, 1500) * _env(
                        int(beat / 2 * 0.9 * SR), 0.01, 0.12), t0 + k * beat / 2, 0.08)
            if mood == "tense":
                for k in range(4):
                    _add(buf, _pluck(note(chord + (k % 2) * 4, 0), 0.3, 2), t0 + k * beat, 0.15)
    return _norm(buf[: int(total * SR)], 0.9)


# ---------------- mix ----------------
def _smooth(x, win):
    """Centered moving average, O(n)."""
    win = max(1, int(win))
    c = np.concatenate([[0.0], np.cumsum(np.pad(x, (win // 2, win - win // 2 - 1), mode="edge"))])
    return (c[win:] - c[:-win]) / win


def mix(spec, tl, path, seed=0):
    rng = np.random.default_rng(seed)
    n = int((tl.total + 0.2) * SR)
    vo, sfx = np.zeros(n), np.zeros(n)
    for ln in tl.lines:
        _add(vo, ln.clip.audio.astype(np.float64), ln.start, spec["shots"][ln.shot].get("vo_gain", 1.0))
    music_gain = np.ones(n)
    for sh in tl.shots:
        d = sh.data
        for fx in d.get("sfx", []):
            _add(sfx, cue_audio(fx["cue"], rng, fx.get("dur"), fx.get("prompt")),
                 sh.start + fx.get("at", 0.0), fx.get("gain", 1.0))
        if d.get("ambience"):
            _add(sfx, cue_audio(d["ambience"], rng, sh.dur, d.get("ambience_prompt")), sh.start, 0.45)
        if d.get("transition") == "glitch":
            _add(sfx, procedural("glitch", rng), sh.start, 0.6)
        if d.get("transition") == "flash":
            _add(sfx, procedural("impact", rng), sh.start, 0.5)
        a, b = int(sh.start * SR), int(sh.end * SR)
        music_gain[a:b] = d.get("music", 1.0)
    music_gain = _smooth(music_gain, int(0.25 * SR))

    mood = spec.get("music", {}).get("mood", "quirky")
    seed_m = int(hashlib.sha1(spec["id"].encode()).hexdigest(), 16) % 10_000
    music = music_bed(mood, tl.total + 0.2, seed_m)[:n]
    music = np.pad(music, (0, n - len(music)))
    # duck the music under dialogue
    venv = _smooth(np.abs(vo), int(0.12 * SR))
    duck = 1 - 0.6 * np.clip(venv / (venv.max() * 0.25 + 1e-9), 0, 1)
    duck = _smooth(duck, int(0.2 * SR))
    level = spec.get("music", {}).get("level", 0.32)
    out = vo + 0.65 * sfx + level * music * duck * music_gain

    fo = int(0.5 * SR)
    out[-fo:] *= np.linspace(1, 0, fo)
    out = np.tanh(_norm(out, 1.0) * 1.15)
    pcm = (_norm(out, 0.89) * 32767).astype(np.int16)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(np.repeat(pcm[:, None], 2, axis=1).tobytes())
    return path
